function telegramEntityToken(index: number): string {
  return "\u0001TG_ENTITY_" + index + "\u0001";
}

function escapeTelegramHtml(value: string): string {
  return value
    .replace(/&/gu, "&amp;")
    .replace(/</gu, "&lt;")
    .replace(/>/gu, "&gt;")
    .replace(/"/gu, "&quot;");
}

function renderTelegramInlineMarkdown(value: string, stash: (html: string) => string): string {
  let text = value;

  // Keep code literal so its symbols cannot become formatting tags.
  text = text.replace(/\x60([^\x60\n]+)\x60/gu, (_match, code: string) =>
    stash("<code>" + escapeTelegramHtml(code) + "</code>"),
  );

  // Only allow web links. Other schemes remain visible plain text.
  text = text.replace(/\[([^\]\n]+)\]\((https?:\/\/[^\s)]+)\)/giu, (_match, label: string, url: string) =>
    stash('<a href="' + escapeTelegramHtml(url) + '">' + escapeTelegramHtml(label) + "</a>"),
  );

  text = escapeTelegramHtml(text);

  // Common Markdown emphasis emitted by language models and human-authored
  // bot copy. Single asterisks are treated as bold for familiar Telegram UX.
  text = text
    .replace(/\*\*([^\n*]+)\*\*/gu, "<b>$1</b>")
    .replace(/(?<![\p{L}\p{N}])\*([^\s*\n](?:[^*\n]*[^\s*\n])?)\*(?![\p{L}\p{N}])/gu, "<b>$1</b>")
    .replace(/__([^_\n]+)__/gu, "<b>$1</b>")
    .replace(/~~([^~\n]+)~~/gu, "<s>$1</s>");

  return text;
}

/**
 * Render safe, lightweight Markdown as Telegram HTML. Raw HTML from model or
 * user text is escaped; only tags generated by this formatter are emitted.
 */
export function formatTelegramHtml(input: string): string {
  const value = String(input ?? "").replace(/\r\n?/gu, "\n");
  const entities: string[] = [];
  const stash = (html: string): string => {
    const token = telegramEntityToken(entities.length);
    entities.push(html);
    return token;
  };

  let text = value.replace(/\x60{3}(?:[a-z0-9_+-]+)?[ \t]*\n([\s\S]*?)\x60{3}/giu, (_match, code: string) =>
    stash("<pre>" + escapeTelegramHtml(code.replace(/\n+$/u, "")) + "</pre>"),
  );

  const lines = text.split("\n").map((rawLine) => {
    const heading = rawLine.match(/^ {0,3}#{1,3}[ \t]+(.+)$/u);
    let line = heading ? "<b>" + renderTelegramInlineMarkdown(heading[1], stash) + "</b>" : renderTelegramInlineMarkdown(rawLine, stash);

    if (/^(?:🟢[ \t]*)?Final answer$/iu.test(line) || /^परमार्थAI by BRɅIN\.$/u.test(line)) {
      line = "<b>" + line + "</b>";
    } else if (/^(?:📖[ \t]*|👻[ \t]*)?Fatman Mode is (?:ON|OFF)\.$/u.test(line)) {
      line = "<b>" + line + "</b>";
    } else {
      const label = line.match(/^((?:📌[ \t]*)?[^:\n]{1,36}:)([ \t]+.*)?$/u);
      if (label) line = "<b>" + label[1] + "</b>" + (label[2] ?? "");
    }

    if (/^[-*][ \t]+/u.test(line)) line = "• " + line.replace(/^[-*][ \t]+/u, "");
    return line;
  });

  text = lines.join("\n");
  return entities.reduce(
    (rendered, html, index) => rendered.split(telegramEntityToken(index)).join(html),
    text,
  );
}
